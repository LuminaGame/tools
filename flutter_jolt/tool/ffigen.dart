// ignore_for_file: avoid_print

import 'dart:io';

import 'package:ffigen/ffigen.dart';

/// Generates `lib/src/jolt_bindings.g.dart` (`@Native` bindings resolved
/// against the code asset `package:flutter_jolt/src/jolt_native.dart`) from
/// `src/jolt_c.h`.
///
/// Usage: `dart run tool/ffigen.dart` (needs libclang; set `LIBCLANG_PATH`
/// to its folder when it is not found).
void main() {
  final root = Platform.script.resolve('../');
  FfiGenerator(
    headers: Headers(
      entryPoints: [root.resolve('src/jolt_c.h')],
      include: (h) => h.path.endsWith('jolt_c.h'),
    ),
    functions: Functions(
      include: Declarations.includeAll,
      isLeaf: (d) => _leaf(d.originalName),
    ),
    structs: Structs(include: Declarations.includeAll),
    enums: Enums(include: Declarations.includeAll),
    macros: Macros(include: Declarations.includeAll),
    typedefs: Typedefs(include: Declarations.includeAll),
    output: Output(
      dartFile: root.resolve('lib/src/jolt_bindings.g.dart'),
      format: true,
      style: const NativeExternalBindings(
        assetId: 'package:flutter_jolt/src/jolt_native.dart',
      ),
      preamble: '''
// AUTO-GENERATED FILE - DO NOT MODIFY.
// Generated by package:ffigen via tool/ffigen.dart from src/jolt_c.h.

// ignore_for_file: type=lint, unused_import, unused_element
// ignore_for_file: camel_case_types, non_constant_identifier_names
// ignore_for_file: constant_identifier_names
''',
    ),
  ).generate();
  print('Generated lib/src/jolt_bindings.g.dart');
}

/// Calls that never call back into Dart and return quickly are leaf calls
/// (no safepoint transition). A step runs the solver on worker threads and
/// can take milliseconds, so it is not a leaf.
bool _leaf(String name) => !const {
  'jolt_world_create',
  'jolt_world_destroy',
  'jolt_world_step',
  'jolt_world_optimize_broad_phase',
  'jolt_shape_convex_hull',
  'jolt_shape_height_field',
  'jolt_shape_static_compound',
}.contains(name);
